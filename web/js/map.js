  // Настройка интерактивного выпадающего меню навигаторов
  var navDropdownsInitialized = false;
  function setupNavDropdowns() {
    if (navDropdownsInitialized) return;
    navDropdownsInitialized = true;

    function closeAllNavDropdowns() {
      document.querySelectorAll('.nav-dropdown-wrapper.is-open').forEach(function (el) {
        el.classList.remove('is-open', 'drop-up');
        var btn = el.querySelector('.nav-dropdown-toggle');
        if (btn) btn.setAttribute('aria-expanded', 'false');
      });
      document.querySelectorAll('.trauma-card.has-open-dropdown').forEach(function (c) {
        c.classList.remove('has-open-dropdown');
      });
    }

    // Делегированный перехват кликов (включая события внутри попапов карты)
    document.addEventListener('click', function (e) {
      var toggle = e.target.closest('.nav-dropdown-toggle');
      var wrapper = toggle ? toggle.closest('.nav-dropdown-wrapper') : null;

      if (toggle && wrapper) {
        e.preventDefault();
        e.stopPropagation();

        var wasOpen = wrapper.classList.contains('is-open');
        closeAllNavDropdowns();

        if (!wasOpen) {
          var parentCard = wrapper.closest('.trauma-card');
          if (parentCard) {
            parentCard.classList.add('has-open-dropdown');
          }

          // Определяем, нужно ли открывать меню наверх (если внизу мало места)
          var rect = wrapper.getBoundingClientRect();
          var scrollArea = wrapper.closest('.centers-scroll-area');
          var spaceBelow;
          var spaceAbove;

          if (scrollArea) {
            var scrollRect = scrollArea.getBoundingClientRect();
            spaceBelow = scrollRect.bottom - rect.bottom;
            spaceAbove = rect.top - scrollRect.top;
          } else {
            spaceBelow = window.innerHeight - rect.bottom;
            spaceAbove = rect.top;
          }

          if (spaceBelow < 180 && spaceAbove > 180) {
            wrapper.classList.add('drop-up');
          } else {
            wrapper.classList.remove('drop-up');
          }

          wrapper.classList.add('is-open');
          toggle.setAttribute('aria-expanded', 'true');
        }
        return;
      }

      var item = e.target.closest('.nav-menu-item');
      if (item) {
        // Даём ссылке открыться в новой вкладке, затем закрываем выпадающее меню
        setTimeout(closeAllNavDropdowns, 120);
        return;
      }

      if (!e.target.closest('.nav-dropdown-wrapper')) {
        closeAllNavDropdowns();
      }
    }, true);

    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') {
        closeAllNavDropdowns();
      }
    });

    if (map) {
      map.on('movestart zoomstart popupclose', closeAllNavDropdowns);
    }
  }

