  var osmDebounceTimer = null;

  function fetchOsmFacilities(lat, lng, radiusKm) {
    if (!lat || !lng) return;

    clearTimeout(osmDebounceTimer);
    osmDebounceTimer = setTimeout(function () {
      performOsmFetch(lat, lng, radiusKm);
    }, 400);
  }

  function performOsmFetch(lat, lng, radiusKm) {
    var syncBtn = document.getElementById('btn-osm-sync');
    if (syncBtn) {
      syncBtn.classList.add('syncing');
      syncBtn.innerHTML = '<span class="geo-spinner" aria-hidden="true"></span> Загрузка из OSM...';
    }

    var statusEl = document.getElementById('geo-status-badge');
    if (statusEl) {
      statusEl.innerHTML = '<span class="geo-spinner" aria-hidden="true"></span> Поиск свежих отделений в базе данных OpenStreetMap...';
    }

    isOsmSyncing = true;

    // Запрашиваем травмпункты и больницы скорой помощи через открытый API OpenStreetMap (Photon Komoot)
    var queries = [
      'https://photon.komoot.io/api/?q=' + encodeURIComponent('травмпункт') + '&lat=' + lat + '&lon=' + lng + '&limit=25',
      'https://photon.komoot.io/api/?q=' + encodeURIComponent('больница') + '&lat=' + lat + '&lon=' + lng + '&limit=25&osm_tag=amenity:hospital'
    ];

    var fetchPromises = queries.map(function (url) {
      return fetch(url)
        .then(function (res) {
          if (!res.ok) throw new Error('OSM HTTP ' + res.status);
          return res.json();
        })
        .catch(function () { return null; });
    });

    Promise.all(fetchPromises)
      .then(function (results) {
        var addedCount = 0;
        var allFeatures = [];

        results.forEach(function (res) {
          if (res && Array.isArray(res.features)) {
            allFeatures = allFeatures.concat(res.features);
          }
        });

        if (allFeatures.length > 0) {
          addedCount = mergeOsmFeatures(allFeatures, lat, lng, radiusKm);
        }

        isOsmSyncing = false;
        dynamicOsmCount += addedCount;

        if (syncBtn) {
          syncBtn.classList.remove('syncing');
          syncBtn.innerHTML = '🌿 База OSM (' + (addedCount > 0 ? ('+' + addedCount) : 'актуально') + ')';
          setTimeout(function () {
            syncBtn.innerHTML = '🌿 Загрузить из базы OSM';
          }, 3500);
        }

        updateStatusCount();
        renderList();
        renderMarkers();
      })
      .catch(function (err) {
        console.warn('Ошибка при динамической загрузке из OSM:', err);
        isOsmSyncing = false;
        if (syncBtn) {
          syncBtn.classList.remove('syncing');
          syncBtn.innerHTML = '🌿 Загрузить из базы OSM';
        }
        updateStatusCount();
      });
  }

  // Слияние и дедупликация полученных объектов из OpenStreetMap
  function mergeOsmFeatures(features, userLat, userLng, radiusKm) {
    var added = 0;
    var maxDist = radiusKm * 1.35; // Небольшой допуск по радиусу

    features.forEach(function (f) {
      var geom = f.geometry;
      var props = f.properties;
      if (!geom || !geom.coordinates || geom.coordinates.length < 2) return;

      var oLng = geom.coordinates[0];
      var oLat = geom.coordinates[1];
      var dist = calcDistanceKm(userLat, userLng, oLat, oLng);

      if (dist > maxDist) return;

      var rawName = props.name || '';
      var osmVal = props.osm_value || '';

      // Фильтруем объекты, не являющиеся медицинскими
      if (/остановка|аптека|кафе|магазин|банк/i.test(rawName)) return;

      var isHospital = /больниц|госпитал|hospital/i.test(rawName) || osmVal === 'hospital';
      var isTrauma = /травм|emergency|неотлож/i.test(rawName) || !isHospital;

      // Если имя пустое или общее
      var name = rawName || (isHospital ? 'Городская больница (OSM)' : 'Травматологический пункт (OSM)');
      var street = props.street || '';
      var house = props.housenumber || '';
      var city = props.city || currentCity || '';
      var address = (city ? (city + ', ') : '') + (street ? (street + (house ? (', д. ' + house) : '')) : (props.district || 'Адрес по карте OpenStreetMap'));

      // Дедупликация: если в радиусе 250 метров уже есть отделение
      var isDuplicate = centersData.some(function (existing) {
        var dBetweenMeters = calcDistanceKm(oLat, oLng, existing.lat, existing.lng) * 1000;
        return dBetweenMeters < 250;
      });

      if (!isDuplicate) {
        var isChild = /детск|педиатрич/i.test(name) || /детск/i.test(address);
        var isEye = /глаз|офтальм/i.test(name);
        var isBurn = /ожог|комбустиол/i.test(name);
        var is24h = /круглосуточ|24|травм|неотлож/i.test(name);

        var osmId = props.osm_id ? Math.abs(props.osm_id) : Math.floor(Math.random() * 90000 + 10000);

        var newCenter = {
          id: 100000 + (osmId % 800000),
          name: name,
          facilityType: isHospital ? 'hospital' : 'trauma',
          isTrauma: true,
          isHospital: isHospital,
          type: isChild ? 'child' : 'adult',
          specialization: isEye ? 'eye' : (isBurn ? 'burn' : 'general'),
          is24h: is24h,
          address: address,
          metro: props.district || city,
          hours: is24h ? 'Круглосуточно (24/7)' : 'Уточняйте режим работы по телефону',
          lat: oLat,
          lng: oLng,
          desc: 'Отделение найдено в открытой глобальной базе OpenStreetMap. Координаты подтверждены OSM ID ' + osmId + '.',
          city: city,
          distance: dist,
          isOsmLive: true
        };

        centersData.push(newCenter);
        added++;
      }
    });

    if (added > 0) {
      centersData.sort(function (a, b) { return a.distance - b.distance; });
    }

    return added;
  }

  // Обработка координат пользователя
  function handleUserLocation(lat, lng, city) {
    userCoords = { lat: lat, lng: lng };
    if (city) currentCity = city;

    // Метка пользователя на карте (пульсирующая синяя точка)
    var userIcon = L.divIcon({
      className: 'osm-user-beacon',
      html: '<div class="osm-user-dot"><div class="osm-user-pulse"></div></div>',
      iconSize: [18, 18],
      iconAnchor: [9, 9]
    });

    var labelTitle = currentCity ? ('г. ' + currentCity) : 'Ваше местоположение';

    if (userMarker) {
      userMarker.setLatLng([lat, lng]);
      userMarker.setPopupContent('<b>📍 ' + labelTitle + '</b><br>Координаты: ' + lat.toFixed(4) + ', ' + lng.toFixed(4));
    } else {
      userMarker = L.marker([lat, lng], {
        icon: userIcon,
        zIndexOffset: 1000,
        title: labelTitle
      }).addTo(map);

      userMarker.bindPopup('<b>📍 ' + labelTitle + '</b><br>Координаты: ' + lat.toFixed(4) + ', ' + lng.toFixed(4));
    }

    // Обновление круга радиуса
    updateRadiusCircle();

    // Расчет расстояния до всех центров
    var items = VERIFIED_CENTERS.map(function (c) {
      var copy = Object.assign({}, c);
      copy.distance = calcDistanceKm(lat, lng, copy.lat, copy.lng);
      return copy;
    });

    items.sort(function (a, b) { return a.distance - b.distance; });
    centersData = items;

    updateStatusCount();
    renderList();
    renderMarkers();
  }

  // Обновление векторного круга радиуса поиска
  function updateRadiusCircle() {
    if (!map || !userCoords) return;

    if (radiusCircle) {
      radiusCircle.setLatLng([userCoords.lat, userCoords.lng]);
      radiusCircle.setRadius(currentRadius * 1000);
    } else {
      radiusCircle = L.circle([userCoords.lat, userCoords.lng], {
        radius: currentRadius * 1000,
        color: '#88ab7e',
        fillColor: '#88ab7e',
        fillOpacity: 0.08,
        weight: 1.5,
        interactive: false
      }).addTo(map);
    }
  }

  // Фильтрация отделений по категории и радиусу
  function getFilteredCenters() {
    var radiusVal = currentRadius;

    return centersData.filter(function (item) {
      // Фильтр по категории
      if (currentCategory === 'trauma') {
        if (!item.isTrauma && item.facilityType !== 'trauma') return false;
      } else if (currentCategory === 'hospital') {
        if (!item.isHospital && item.facilityType !== 'hospital') return false;
      } else if (currentCategory === '24h') {
        if (!item.is24h) return false;
      } else if (currentCategory === 'child') {
        if (item.type !== 'child') return false;
      } else if (currentCategory === 'eye') {
        if (item.specialization !== 'eye') return false;
      } else if (currentCategory === 'burn') {
        if (item.specialization !== 'burn') return false;
      }

      // Фильтр по расстоянию
      if (item.distance !== undefined && item.distance > radiusVal) {
        return false;
      }

      return true;
    });
  }

