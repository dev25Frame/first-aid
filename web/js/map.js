  // Запрос геолокации пользователя
  function requestBrowserGeolocation() {
    currentCityKey = 'auto';
    var citySelect = document.getElementById('map-city-select');
    if (citySelect && citySelect.value !== 'auto') {
      citySelect.value = 'auto';
    }

    var statusEl = document.getElementById('geo-status-badge');
    if (statusEl) {
      statusEl.innerHTML = '<span class="geo-spinner" aria-hidden="true"></span> Определение геопозиции через GPS...';
      statusEl.classList.remove('geo-active');
    }

    if (!navigator.geolocation) {
      handleUserLocation(55.753215, 37.622504, 'Москва');
      if (statusEl) statusEl.innerHTML = '📍 Геолокация не поддерживается. Показана Москва.';
      return;
    }

    navigator.geolocation.getCurrentPosition(
      function (pos) {
        var lat = pos.coords.latitude;
        var lng = pos.coords.longitude;
        handleUserLocation(lat, lng, '');
        if (map) {
          map.flyTo([lat, lng], 12, { duration: 0.8 });
        }
        // Фоновое обратное геокодирование через Nominatim OSM
        reverseGeocodeNominatim(lat, lng);
        // Динамическая подгрузка учреждений из открытой базы OpenStreetMap
        fetchOsmFacilities(lat, lng, currentRadius);
      },
      function (err) {
        console.warn('GPS недоступен, fallback на Москву:', err.message);
        handleUserLocation(55.753215, 37.622504, 'Москва');
        if (statusEl) {
          statusEl.innerHTML = '📍 Геолокация отклонена. Показаны отделения по умолчанию (Москва).';
          statusEl.classList.add('geo-active');
        }
        // Подгрузка для Москвы
        fetchOsmFacilities(55.753215, 37.622504, currentRadius);
      },
      { timeout: 8000, enableHighAccuracy: true }
    );
  }

  // Определение названия населенного пункта через бесплатный Nominatim
  function reverseGeocodeNominatim(lat, lng) {
    var url = 'https://nominatim.openstreetmap.org/reverse?format=json&lat=' + lat + '&lon=' + lng + '&accept-language=ru';
    fetch(url)
      .then(function (res) { return res.json(); })
      .then(function (data) {
        var addr = data && data.address;
        var city = addr && (addr.city || addr.town || addr.village || addr.municipality || addr.state || '');
        if (city) {
          currentCity = city;
          updateStatusCount();
        }
      })
      .catch(function () {});
  }

